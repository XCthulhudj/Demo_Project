clc;
clear;
close all;

%% =========================================================
% MLP 直观仿真
%
% 目标：
%       y = x^2
%
% 网络：
%       1输入
%          ↓
%      10个隐藏神经元
%          ↓
%       1输出
%
% 数据：
%       80个训练样本
%       120个测试样本
%
% 训练过程中实时观察：
%       1. 训练数据
%       2. 测试数据
%       3. 真实函数
%       4. MLP预测曲线
%       5. Train Loss
%       6. Test Loss
%% =========================================================


%% =========================================================
% 1. 生成数据
%% =========================================================

rng(1);

% 先生成200个数据点
X_all = linspace(-2, 2, 200);
Y_all = X_all.^2;

% 打乱索引
idx = randperm(length(X_all));

% 80个训练样本
train_idx = idx(1:80);

% 120个测试样本
test_idx = idx(81:end);

X_train = X_all(train_idx);
Y_train = Y_all(train_idx);

X_test = X_all(test_idx);
Y_test = Y_all(test_idx);

% 排序，方便画图
[X_train, sort_train] = sort(X_train);
Y_train = Y_train(sort_train);

[X_test, sort_test] = sort(X_test);
Y_test = Y_test(sort_test);

% 训练样本数量
m = length(X_train);


%% =========================================================
% 2. MLP结构
%% =========================================================

input_size  = 1;
hidden_size = 10;
output_size = 1;


%% =========================================================
% 3. 初始化参数
%% =========================================================

W1 = randn(hidden_size, input_size) * 0.5;
b1 = zeros(hidden_size, 1);

W2 = randn(output_size, hidden_size) * 0.5;
b2 = 0;


%% =========================================================
% 4. 超参数
%% =========================================================

learning_rate = 0.01;

epochs = 20000;

% 每隔多少轮更新一次图
plot_interval = 200;


%% =========================================================
% 5. 保存Loss
%% =========================================================

train_loss_history = zeros(epochs, 1);
test_loss_history  = zeros(epochs, 1);


%% =========================================================
% 6. 创建动态画图窗口
%% =========================================================

figure;

% ---------------------------------------------------------
% 左边：曲线拟合情况
% ---------------------------------------------------------

subplot(1, 2, 1);

h_true = plot(X_all, Y_all, ...
    'k-', 'LineWidth', 2);

hold on;

h_train = plot(X_train, Y_train, ...
    'bo', ...
    'MarkerSize', 5, ...
    'LineWidth', 1.2);

h_test = plot(X_test, Y_test, ...
    'rx', ...
    'MarkerSize', 5, ...
    'LineWidth', 1.2);

% 初始MLP曲线
X_plot = linspace(-2, 2, 300);

h_pred = plot(X_plot, zeros(size(X_plot)), ...
    'g--', ...
    'LineWidth', 2);

xlabel('x');
ylabel('y');

title('MLP学习 y = x^2');

legend( ...
    '真实函数', ...
    '训练集', ...
    '测试集', ...
    'MLP预测', ...
    'Location', 'northwest');

grid on;

xlim([-2 2]);
ylim([-0.5 4.5]);


% ---------------------------------------------------------
% 右边：Loss
% ---------------------------------------------------------

subplot(1, 2, 2);

h_train_loss = plot( ...
    1:epochs, ...
    zeros(epochs,1), ...
    'b-', ...
    'LineWidth', 1.5);

hold on;

h_test_loss = plot( ...
    1:epochs, ...
    zeros(epochs,1), ...
    'r-', ...
    'LineWidth', 1.5);

xlabel('Epoch');

ylabel('Loss');

title('训练过程');

legend( ...
    'Train Loss', ...
    'Test Loss');

grid on;

xlim([1 epochs]);


%% =========================================================
% 7. 开始训练
%% =========================================================

for epoch = 1:epochs

    %% =====================================================
    % 一、前向传播
    %% =====================================================

    % -----------------------------------------------------
    % 第一层
    %
    % W1 : 10×1
    % X  : 1×80
    %
    % Z1 : 10×80
    % -----------------------------------------------------

    Z1 = W1 * X_train + b1;

    % tanh激活
    A1 = tanh(Z1);


    % -----------------------------------------------------
    % 第二层
    %
    % W2 : 1×10
    % A1 : 10×80
    %
    % Z2 : 1×80
    % -----------------------------------------------------

    Z2 = W2 * A1 + b2;

    % 输出层线性
    A2 = Z2;


    %% =====================================================
    % 二、训练Loss
    %% =====================================================

    train_loss = mean((A2 - Y_train).^2) / 2;

    train_loss_history(epoch) = train_loss;


    %% =====================================================
    % 三、反向传播
    %% =====================================================

    % -----------------------------------------------------
    % 输出层
    %
    % L = 1/2 (A2-Y)^2
    %
    % dL/dA2 = A2-Y
    % -----------------------------------------------------

    dA2 = A2 - Y_train;

    % 输出层线性
    dZ2 = dA2;


    % -----------------------------------------------------
    % 第二层权重
    %
    % dW2 = dZ2 * A1'
    % -----------------------------------------------------

    dW2 = (dZ2 * A1') / m;

    % 第二层偏置
    db2 = sum(dZ2, 2) / m;


    % -----------------------------------------------------
    % 梯度继续向前
    %
    % dA1 = W2' * dZ2
    % -----------------------------------------------------

    dA1 = W2' * dZ2;


    % -----------------------------------------------------
    % 穿过tanh
    %
    % tanh导数：
    %
    % 1 - A1^2
    % -----------------------------------------------------

    dZ1 = dA1 .* (1 - A1.^2);


    % -----------------------------------------------------
    % 第一层
    %
    % dW1 = dZ1 * X'
    % -----------------------------------------------------

    dW1 = (dZ1 * X_train') / m;

    % 第一层偏置
    db1 = sum(dZ1, 2) / m;


    %% =====================================================
    % 四、梯度下降
    %% =====================================================

    W2 = W2 - learning_rate * dW2;

    b2 = b2 - learning_rate * db2;

    W1 = W1 - learning_rate * dW1;

    b1 = b1 - learning_rate * db1;


    %% =====================================================
    % 五、测试
    %
    % 注意：
    %
    % 测试集只进行前向传播
    %
    % 不参与反向传播
    % 不更新W和b
    %% =====================================================

    Z1_test = W1 * X_test + b1;

    A1_test = tanh(Z1_test);

    Z2_test = W2 * A1_test + b2;

    A2_test = Z2_test;

    test_loss = mean((A2_test - Y_test).^2) / 2;

    test_loss_history(epoch) = test_loss;


    %% =====================================================
    % 六、动态显示
    %% =====================================================

    if mod(epoch, plot_interval) == 0

        % -------------------------------------------------
        % 计算当前MLP曲线
        % -------------------------------------------------

        Z1_plot = W1 * X_plot + b1;

        A1_plot = tanh(Z1_plot);

        Z2_plot = W2 * A1_plot + b2;

        Y_plot_pred = Z2_plot;


        % -------------------------------------------------
        % 更新MLP曲线
        % -------------------------------------------------

        set(h_pred, ...
            'YData', Y_plot_pred);


        % -------------------------------------------------
        % 更新Loss曲线
        % -------------------------------------------------

        set(h_train_loss, ...
            'YData', train_loss_history);

        set(h_test_loss, ...
            'YData', test_loss_history);


        % 自动调整Loss纵坐标
        max_loss = max( ...
            train_loss_history(1:epoch));

        max_test_loss = max( ...
            test_loss_history(1:epoch));

        max_loss = max(max_loss, max_test_loss);

        if max_loss > 0
            ylim([0 max_loss * 1.1]);
        end


        % -------------------------------------------------
        % 标题显示当前训练状态
        % -------------------------------------------------

        subplot(1, 2, 1);

        title(sprintf( ...
            'MLP学习 y = x^2   Epoch = %d', ...
            epoch));


        subplot(1, 2, 2);

        title(sprintf( ...
            'Train Loss = %.6f   Test Loss = %.6f', ...
            train_loss, test_loss));


        drawnow;

    end

end


%% =========================================================
% 8. 最终测试
%% =========================================================

fprintf('\n=============================\n');
fprintf('训练完成\n');
fprintf('=============================\n');

fprintf('最终 Train Loss = %.8f\n', ...
    train_loss_history(end));

fprintf('最终 Test Loss  = %.8f\n', ...
    test_loss_history(end));


%% =========================================================
% 9. 输出测试结果
%% =========================================================

fprintf('\n测试集预测：\n');

test_x = [-2 -1 0 1 2];

for i = 1:length(test_x)

    x = test_x(i);

    z1 = W1 * x + b1;

    a1 = tanh(z1);

    y_pred = W2 * a1 + b2;

    fprintf( ...
        'x = %5.2f, 真实值 = %5.3f, MLP = %7.4f\n', ...
        x, x^2, y_pred);

end