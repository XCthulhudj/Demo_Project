%% =========================================================
%  MLP 手写实现
%  网络结构：2输入 -> 4隐藏神经元 -> 1输出
%  任务：XOR
%
%  不使用 MATLAB Neural Network Toolbox
%  手动实现：
%  1. 前向传播
%  2. 损失函数
%  3. 反向传播
%  4. 梯度下降
%% =========================================================


%% 1. 训练数据
%
% 每一列代表一个样本
%
% X =
% [ x1 x1 x1 x1
%   x2 x2 x2 x2 ]

X = [
    0  0  1  1;
    0  1  0  1
];

% XOR真实输出
Y = [
    0  1  1  0
];


%% 2. 网络参数

input_size  = 2;    % 输入层神经元数
hidden_size = 4;    % 隐藏层神经元数
output_size = 1;    % 输出层神经元数

% 样本数量
m = size(X, 2);


%% 3. 初始化权重和偏置

rng(42);   % 固定随机种子，方便重复实验

% 第一层
%
% W1尺寸：
% hidden_size × input_size
%
% 4 × 2

W1 = randn(hidden_size, input_size) * 0.5;

% b1：
% 4 × 1

b1 = zeros(hidden_size, 1);


% 第二层
%
% W2尺寸：
% output_size × hidden_size
%
% 1 × 4

W2 = randn(output_size, hidden_size) * 0.5;

% b2：
% 1 × 1

b2 = 0;


%% 4. 学习率和训练次数

learning_rate = 1.0;

epochs = 20000;


%% 5. 保存损失，用于画图

loss_history = zeros(epochs, 1);


%% =========================================================
%                    开始训练
%% =========================================================

for epoch = 1:epochs

    %% -----------------------------------------------------
    %  一、前向传播
    %% -----------------------------------------------------

    % 第一层：
    %
    % Z1 = W1 * X + b1
    %
    % W1 : 4×2
    % X  : 2×4
    % b1 : 4×1
    %
    % Z1 : 4×4

    Z1 = W1 * X + b1;


    % 隐藏层激活
    %
    % A1 = sigmoid(Z1)

    A1 = sigmoid(Z1);


    % 第二层
    %
    % Z2 = W2 * A1 + b2
    %
    % W2 : 1×4
    % A1 : 4×4
    % b2 : 1×1
    %
    % Z2 : 1×4

    Z2 = W2 * A1 + b2;


    % 输出层
    %
    % A2 = sigmoid(Z2)

    A2 = sigmoid(Z2);


    %% -----------------------------------------------------
    %  二、计算损失
    %% -----------------------------------------------------

    % 使用：
    %
    % L = 1/(2m) * sum((A2-Y)^2)

    loss = sum((A2 - Y).^2, "all") / (2 * m);

    loss_history(epoch) = loss;


    %% -----------------------------------------------------
    %  三、反向传播
    %% -----------------------------------------------------

    % =====================================================
    % 输出层
    %
    % L = 1/2 * (A2-Y)^2
    %
    % dL/dA2 = A2-Y
    %
    % A2 = sigmoid(Z2)
    %
    % dA2/dZ2 = A2 .* (1-A2)
    %
    % 所以：
    %
    % dZ2 = dL/dZ2
    %     = (A2-Y) .* A2 .* (1-A2)
    % =====================================================

    dZ2 = (A2 - Y) .* A2 .* (1 - A2);


    % -----------------------------------------------------
    % 第二层权重梯度
    %
    % Z2 = W2*A1+b2
    %
    % dW2 = dZ2 * A1'
    %
    % 尺寸：
    %
    % dZ2 : 1×4
    % A1' : 4×4
    %
    % dW2 : 1×4
    % -----------------------------------------------------

    dW2 = (dZ2 * A1') / m;


    % 第二层偏置梯度
    %
    % db2 = sum(dZ2)

    db2 = sum(dZ2, 2) / m;


    % =====================================================
    % 梯度继续向前传播
    %
    % dA1 = dZ2 * W2
    %
    % 写成矩阵形式：
    %
    % dA1 = W2' * dZ2
    %
    % W2' : 4×1
    % dZ2 : 1×4
    %
    % dA1 : 4×4
    % =====================================================

    dA1 = W2' * dZ2;


    % -----------------------------------------------------
    % 穿过隐藏层 Sigmoid
    %
    % A1 = sigmoid(Z1)
    %
    % dA1/dZ1 = A1 .* (1-A1)
    %
    % 所以：
    %
    % dZ1 = dA1 .* A1 .* (1-A1)
    % -----------------------------------------------------

    dZ1 = dA1 .* A1 .* (1 - A1);


    % -----------------------------------------------------
    % 第一层权重梯度
    %
    % Z1 = W1*X+b1
    %
    % dW1 = dZ1 * X'
    %
    % dZ1 : 4×4
    % X'  : 4×2
    %
    % dW1 : 4×2
    % -----------------------------------------------------

    dW1 = (dZ1 * X') / m;


    % 第一层偏置梯度

    db1 = sum(dZ1, 2) / m;


    %% -----------------------------------------------------
    %  四、梯度下降，更新参数
    %% -----------------------------------------------------

    W2 = W2 - learning_rate * dW2;

    b2 = b2 - learning_rate * db2;

    W1 = W1 - learning_rate * dW1;

    b1 = b1 - learning_rate * db1;


    %% -----------------------------------------------------
    %  输出训练过程
    %% -----------------------------------------------------

    if mod(epoch, 1000) == 0
        fprintf("Epoch = %5d, Loss = %.8f\n", epoch, loss);
    end

end


%% =========================================================
%                    训练结束
%% =========================================================

fprintf("\n=============================\n");
fprintf("训练结束\n");
fprintf("=============================\n");


%% 6. 再进行一次前向传播

Z1 = W1 * X + b1;

A1 = sigmoid(Z1);

Z2 = W2 * A1 + b2;

A2 = sigmoid(Z2);


%% 7. 输出最终预测结果

fprintf("\n真实值：\n");
disp(Y);

fprintf("预测概率：\n");
disp(A2);


% 四舍五入得到最终分类结果
Y_pred = round(A2);

fprintf("预测结果：\n");
disp(Y_pred);


%% 8. 计算最终准确率

accuracy = sum(Y_pred == Y, "all") / numel(Y);

fprintf("准确率：%.2f%%\n", accuracy * 100);


%% 9. 绘制损失曲线

figure;

plot(1:epochs, loss_history, 'LineWidth', 1.5);

xlabel("Epoch");

ylabel("Loss");

title("MLP Training Loss");

grid on;


%% =========================================================
%                    Sigmoid函数
%% =========================================================

function y = sigmoid(x)

    y = 1 ./ (1 + exp(-x));

end
